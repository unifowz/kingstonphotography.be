#!/usr/bin/env python3
"""Scan album folders. No packages needed; Python 3.9 or later.

python update_albums.py         -> regenerate albums.js for static hosting
python update_albums.py --serve -> local preview; scan again on every refresh
"""
import argparse
import json
import re
import sys
import webbrowser
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import quote, urlsplit

ROOT = Path(__file__).resolve().parent
EXTENSIONS = {'.jpg', '.jpeg', '.png', '.webp', '.avif', '.gif'}


def natural_key(path):
    return [int(part) if part.isdigit() else part.casefold()
            for part in re.split(r'(\d+)', path.name)]


def image_size(path):
    """(width, height) as displayed, read from the file header; None when unknown."""
    try:
        with path.open('rb') as f:
            head = f.read(24)
            if head[:4] == bytes([0x89, 0x50, 0x4E, 0x47]) and head[12:16] == b'IHDR':
                return int.from_bytes(head[16:20], 'big'), int.from_bytes(head[20:24], 'big')
            if head[:2] != bytes([0xFF, 0xD8]):
                return None
            f.seek(2)
            rotated = False
            while True:
                marker = f.read(2)
                if len(marker) < 2 or marker[0] != 0xFF:
                    return None
                length = int.from_bytes(f.read(2), 'big')
                if marker[1] == 0xE1:
                    segment = f.read(length - 2)
                    rotated = exif_rotated(segment) or rotated
                    continue
                if marker[1] in (0xC0, 0xC1, 0xC2, 0xC3, 0xC5, 0xC6, 0xC7, 0xC9, 0xCA, 0xCB, 0xCD, 0xCE, 0xCF):
                    data = f.read(5)
                    height, width = int.from_bytes(data[1:3], 'big'), int.from_bytes(data[3:5], 'big')
                    return (height, width) if rotated else (width, height)
                f.seek(length - 2, 1)
    except OSError:
        return None


def exif_rotated(segment):
    """True when the EXIF orientation turns the photo a quarter (values 5 to 8)."""
    if segment[:6] != b'Exif' + bytes(2):
        return False
    tiff = segment[6:]
    order = 'little' if tiff[:2] == b'II' else 'big'
    offset = int.from_bytes(tiff[4:8], order)
    count = int.from_bytes(tiff[offset:offset + 2], order)
    for i in range(count):
        entry = tiff[offset + 2 + i * 12:offset + 14 + i * 12]
        if int.from_bytes(entry[:2], order) == 0x0112:
            return int.from_bytes(entry[8:10], order) in (5, 6, 7, 8)
    return False


def scan_albums(root=ROOT):
    folder = root / 'albums'
    folder.mkdir(exist_ok=True)
    albums = []
    for album in sorted(folder.iterdir(), key=natural_key):
        if album.name.startswith('.') or album.is_symlink() or not album.is_dir():
            continue
        photos = []
        for photo in sorted(album.iterdir(), key=natural_key):
            if (photo.name.startswith('.') or photo.is_symlink() or not photo.is_file()
                    or photo.suffix.lower() not in EXTENSIONS):
                continue
            entry = {'name': photo.stem,
                     'src': '/'.join(quote(part, safe='') for part in photo.relative_to(root).parts)}
            size = image_size(photo)
            if size:
                entry['width'], entry['height'] = size
            photos.append(entry)
        if photos:
            albums.append({'name': album.name, 'photos': photos})
    return albums


def render_manifest(root=ROOT):
    return ('// Generated by update_albums.py; edit folders in albums/ instead.\n'
            'window.KINGSTON_ALBUMS = ' + json.dumps(scan_albums(root), ensure_ascii=True, indent=2) + ';\n')


def build(root=ROOT):
    contents = render_manifest(root)
    temporary = root / 'albums.js.tmp'
    temporary.write_text(contents, encoding='utf-8')
    temporary.replace(root / 'albums.js')
    albums = scan_albums(root)
    print(f"Updated: {len(albums)} albums, {sum(len(a['photos']) for a in albums)} photos.")


class PreviewHandler(SimpleHTTPRequestHandler):
    def end_headers(self):
        self.send_header('Cache-Control', 'no-store')
        super().end_headers()

    def do_GET(self):
        if urlsplit(self.path).path == '/albums.js':
            data = render_manifest().encode('utf-8')
            self.send_response(200)
            self.send_header('Content-Type', 'text/javascript; charset=utf-8')
            self.send_header('Content-Length', str(len(data)))
            self.end_headers()
            self.wfile.write(data)
        else:
            super().do_GET()

    def list_directory(self, path):
        self.send_error(404)
        return None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--serve', action='store_true')
    parser.add_argument('--port', type=int, default=8000)
    parser.add_argument('--no-browser', action='store_true')
    args = parser.parse_args()
    build()
    if not args.serve:
        return
    server = ThreadingHTTPServer(('127.0.0.1', args.port), partial(PreviewHandler, directory=str(ROOT)))
    url = f'http://127.0.0.1:{args.port}/'
    print(f'Preview: {url}\nRefresh the browser after changing photos or folders. Ctrl+C to stop.', flush=True)
    if not args.no_browser:
        webbrowser.open(url)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()


if __name__ == '__main__':
    try:
        main()
    except OSError as error:
        print(f'Could not update/start: {error}', file=sys.stderr)
        sys.exit(1)
